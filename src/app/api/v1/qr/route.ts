import { connection } from 'next/server'
import { qrPng, qrSvg } from '@/server/qr'

/**
 * GET /api/v1/qr?format=svg|png[&download=1] — the menu QR code (FR-018). Public: it only
 * encodes the public menu URL. `download=1` makes the browser save it as a file.
 */
export async function GET(request: Request): Promise<Response> {
  await connection()
  const params = new URL(request.url).searchParams
  const format = params.get('format') === 'png' ? 'png' : 'svg'
  const headers = new Headers({
    'Cache-Control': 'public, max-age=3600',
    'X-Content-Type-Options': 'nosniff',
  })
  if (params.get('download') === '1')
    headers.set('Content-Disposition', `attachment; filename="zorko-sangli-menu-qr.${format}"`)
  if (format === 'png') {
    headers.set('Content-Type', 'image/png')
    return new Response(new Uint8Array(await qrPng()), { headers })
  }
  headers.set('Content-Type', 'image/svg+xml; charset=utf-8')
  // The SVG contains only paths generated by `qrcode`; sandbox it anyway if opened directly.
  headers.set('Content-Security-Policy', "default-src 'none'; style-src 'unsafe-inline'; sandbox")
  return new Response(await qrSvg(), { headers })
}
